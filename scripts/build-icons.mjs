// Builds src/icons/data.ts from icons/*.json (see icon-paint.mjs for the source format).
//   node scripts/build-icons.mjs           write it
//   node scripts/build-icons.mjs --check   fail when it is out of date (npm run check)
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { iconPaths } from './icon-paint.mjs'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const target = join(root, 'src', 'icons', 'data.ts')
const sources = ['existing.json', 'new.json'].map((file) =>
  JSON.parse(readFileSync(join(root, 'icons', file), 'utf8'))
)

const icons = {}
for (const source of sources) {
  for (const [name, icon] of Object.entries(source)) {
    if (icons[name]) throw new Error(`icon "${name}" is defined twice`)
    if (!/^[a-z][A-Za-z0-9]*$/.test(name)) throw new Error(`icon name "${name}" is not camelCase`)
    icons[name] = { group: icon.group, ...iconPaths(icon) }
  }
}

const names = Object.keys(icons).sort()
const lines = [
  '// Generated by scripts/build-icons.mjs from icons/*.json: do not edit by hand.',
  '/* eslint-disable */',
  '',
  'export const ICON_DATA = {',
  ...names.map((name) => {
    const { group, a, b } = icons[name]
    return `  ${name}: { group: ${JSON.stringify(group)}, a: ${JSON.stringify(a)}, b: ${JSON.stringify(b)} },`
  }),
  '} as const',
  ''
]
const text = lines.join('\n')

if (process.argv.includes('--check')) {
  let current = ''
  try {
    current = readFileSync(target, 'utf8')
  } catch {
    // missing: out of date
  }
  if (current !== text) {
    console.error('src/icons/data.ts is out of date: run npm run icons')
    process.exit(1)
  }
  console.log(`${names.length} icons up to date`)
} else {
  writeFileSync(target, text)
  console.log(`${names.length} icons written`)
}
